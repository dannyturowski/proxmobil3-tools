#!/usr/bin/env python3
"""wt32-r4 (from wt32-r2): regenerate firmware/sdkconfig.defaults.

base      = the Arduino 2.0.17 SDK's own sdkconfig (what the precompiled r1 libraries were built with)
overrides = firmware/sdkconfig.r4-overrides
The base's "Deprecated options for backward compatibility" block (old aliases of the same symbols,
e.g. CONFIG_TCPIP_TASK_STACK_SIZE) is dropped so an alias can never fight an override.  Every symbol
mentioned in the overrides (as CONFIG_X=... or "# CONFIG_X is not set") is removed from the base, then
the overrides are appended, so each symbol is assigned exactly once.

  python3 tools/gen_sdkconfig_defaults.py [BASE_SDKCONFIG]
  default BASE: $PLATFORMIO_CORE_DIR/packages/framework-arduinoespressif32/tools/sdk/esp32/sdkconfig
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYM = re.compile(r'^(?:# )?(CONFIG_[A-Za-z0-9_]+)(?:=| is not set)')


def symbols(lines):
    return {m.group(1) for m in map(SYM.match, lines) if m}


def main(argv):
    base_path = argv[1] if len(argv) > 1 else os.path.join(os.environ.get('PLATFORMIO_CORE_DIR', os.path.expanduser('~/.platformio')), 'packages',
        'framework-arduinoespressif32', 'tools', 'sdk', 'esp32', 'sdkconfig')
    ovr_path = os.path.join(ROOT, 'firmware', 'sdkconfig.r4-overrides')
    with open(base_path, encoding='utf-8') as f:
        base_text = f.read()
    with open(ovr_path, encoding='utf-8') as f:
        ovr = f.read().splitlines()
    drop = symbols(ovr)
    lines = base_text.splitlines()
    a, b = lines.index('# Deprecated options for backward compatibility'), lines.index('# End of deprecated options')
    lines = lines[:a] + lines[b + 1:]
    kept = [l for l in lines if not (SYM.match(l) and SYM.match(l).group(1) in drop)]
    out = ['# GENERATED by tools/gen_sdkconfig_defaults.py -- edit firmware/sdkconfig.r4-overrides instead.',
           '# base: Arduino 2.0.17 SDK sdkconfig (framework-arduinoespressif32 3.20017.241212), sha256 %s'
           % hashlib.sha256(base_text.encode()).hexdigest(),
           ''] + kept + ['', '# ======== wt32-r4 overrides (firmware/sdkconfig.r4-overrides) ========'] + ovr
    dst = os.path.join(ROOT, 'firmware', 'sdkconfig.defaults')
    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%s: %d base lines kept, %d symbols overridden' % (dst, len(kept), len(drop)))


if __name__ == '__main__':
    main(sys.argv)
